class TextEmbedder:
    """Instant offline semantic and lexical embedder.
    Uses TF-IDF with character & word n-grams (1, 3) and cosine similarity
    for millisecond retrieval with zero network or download delays.
    Optionally falls back to SentenceTransformer if USE_HF_EMBEDDINGS=1.
    """

    def __init__(self):
        import os
        self._use_hf = os.environ.get("USE_HF_EMBEDDINGS", "0") == "1"
        self._st_model = None

    def similarity_scores(self, query: str, candidate_texts: List[str]) -> List[float]:
        """Calculates cosine similarity between query and candidate texts."""
        if not candidate_texts:
            return []

        # If user explicitly opted into heavy HF embeddings
        if self._use_hf:
            try:
                if self._st_model is None:
                    from sentence_transformers import SentenceTransformer
                    self._st_model = SentenceTransformer("all-MiniLM-L6-v2")
                embeddings = self._st_model.encode([query] + candidate_texts, convert_to_numpy=True, show_progress_bar=False)
                q_emb = embeddings[0]
                c_embs = embeddings[1:]
                q_norm = np.linalg.norm(q_emb) or 1.0
                c_norms = np.linalg.norm(c_embs, axis=1)
                c_norms[c_norms == 0] = 1.0
                dots = np.dot(c_embs, q_emb)
                return (dots / (q_norm * c_norms)).tolist()
            except Exception:
                pass

        # High-performance instant TF-IDF with sublinear scaling
        from sklearn.feature_extraction.text import TfidfVectorizer
        from sklearn.metrics.pairwise import cosine_similarity
        try:
            vec = TfidfVectorizer(
                ngram_range=(1, 2),
                sublinear_tf=True,
                stop_words='english'
            )
            mat = vec.fit_transform([query] + candidate_texts)
            sims = cosine_similarity(mat[0:1], mat[1:])[0]
            return sims.tolist()
        except Exception:
            # Keyword overlap fallback
            q_words = set(re.findall(r"\w+", query.lower()))
            scores = []
            for t in candidate_texts:
                t_words = set(re.findall(r"\w+", t.lower()))
                overlap = len(q_words.intersection(t_words))
                scores.append(float(overlap) / (len(q_words) or 1.0))
            return scores


# Global singleton embedder
_EMBEDDER = TextEmbedder()


class SchemaRetriever:
    """RAG Retriever that indexes database tables and uses semantic matching +

    relationship-aware graph bridge expansion to select the right tables.
    """

    def __init__(self, db_manager):
        self.db = db_manager
        self.tables = self.db.get_tables()
        self._table_descriptions: Dict[str, str] = {}
        self._build_table_descriptions()

    def _build_table_descriptions(self):
        """Constructs rich text summaries for each table based on columns, types, and FKs."""
        for table in self.tables:
            schema = self.db.get_table_schema(table)
            cols = [c["name"] for c in schema["columns"]]
            fks = [f"linked to {fk['to_table']}" for fk in schema["foreign_keys"]]

            desc_parts = [
                f"Table {table}",
                f"Columns: {', '.join(cols)}",
            ]
            if fks:
                desc_parts.append(f"Relationships: {', '.join(fks)}")

            self._table_descriptions[table] = ". ".join(desc_parts)

    def retrieve_tables(self, question: str, top_k: int = 4, auto_bridge: bool = True) -> Tuple[List[str], List[str]]:
        """Retrieves top_k relevant tables, then adds intermediate foreign key bridge tables.

        Returns (all_selected_tables, bridge_tables_added).
        """
        if len(self.tables) <= 5:
            # If the database is small (e.g. 5 tables or fewer), include all tables to guarantee 100% accuracy
            return list(self.tables), []

        candidate_tables = list(self.tables)
        candidate_texts = [self._table_descriptions[t] for t in candidate_tables]

        # Calculate semantic similarity
        scores = _EMBEDDER.similarity_scores(question, candidate_texts)
        table_scores = list(zip(candidate_tables, scores))
        table_scores.sort(key=lambda x: x[1], reverse=True)

        # Select top_k tables
        selected = [t for t, s in table_scores[:top_k]]

        # Relationship-aware Bridge Expansion
        if auto_bridge and len(selected) > 1:
            bridged_set = self.db.find_relationship_bridges(selected)
            added_bridges = list(bridged_set - set(selected))
            full_selection = list(bridged_set)
        else:
            added_bridges = []
            full_selection = selected

        return full_selection, added_bridges


class FewShotRetriever:
    """Retrieves top-N most similar Golden Query examples (Question, SQL, Explanation)

    to inject into the LLM context.
    """

    def __init__(self, custom_examples: Optional[List[Dict[str, str]]] = None):
        self.examples = (custom_examples or []) + CHINOOK_GOLDEN_EXAMPLES + ECOMMERCE_GOLDEN_EXAMPLES
        self.example_questions = [ex["question"] for ex in self.examples]

    def retrieve_few_shots(self, question: str, top_k: int = 2) -> List[Dict[str, str]]:
        """Returns the top_k most relevant verified question-to-SQL examples."""
        if not self.examples:
            return []

        scores = _EMBEDDER.similarity_scores(question, self.example_questions)
        ranked = sorted(zip(self.examples, scores), key=lambda x: x[1], reverse=True)
        return [ex for ex, score in ranked[:top_k]]
